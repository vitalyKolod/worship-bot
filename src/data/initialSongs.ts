export interface InitialSong {
  title: string;
  tempo?: number;
  key: string;
  timeSignature: "4/4";
  notes?: string;
}

const UNKNOWN_KEY = "не знаю";

function song(
  title: string,
  tempo?: number,
  key = UNKNOWN_KEY,
  notes?: string
): InitialSong {
  return {
    title,
    ...(tempo === undefined ? {} : { tempo }),
    key,
    timeSignature: "4/4",
    ...(notes ? { notes } : {}),
  };
}

